#include "cub.h"

void	ft_putendl_fd(char *s, int fd)
{
	while (*s)
	{
		if (write(fd, s, 1) < 0)
			return ;
		s++;
	}
	if (write(fd, "\n", 1) < 0)
		return ;
}
